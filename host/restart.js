/**
 * The auto-restart helper for dsh-web-update.
 *
 * A self-update replaces the running dsh package on disk, so the Host process
 * must exit and a fresh `dsh web` must take the same port. The Host cannot do
 * that in its own process tree (children die with it, and a terminal signal
 * reaches the whole foreground group), so it writes this small bash script,
 * starts it detached in its own session, and lets it outlive the exit.
 *
 * The helper: waits for the old pid to disappear, waits for the port to be
 * released, starts the exact same command line, waits until the new process is
 * both alive and accepting TCP connections, and rolls the package back when the
 * new server never comes up. Every step is appended to the update log and the
 * final outcome is written to `last-restart.json`, which the plugin reports on
 * the next start.
 */
import { spawn } from 'node:child_process'
import { chmodSync, mkdirSync, writeFileSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'

/** Shell single-quote quoting. */
function quote(value) {
  return `'${String(value).replaceAll("'", `'\\''`)}'`
}

/** Quote an array as a bash array literal. */
function arrayLiteral(values) {
  return `( ${values.map((value) => quote(value)).join(' ')} )`
}

/** Return the target string for one npm argument template. */
export function expandTarget(template, target) {
  return template.map((argument) => String(argument).replaceAll('{target}', target))
}

/** Default directory that keeps logs, the helper script and the last status. */
export function defaultStateDir(dshHome = process.env.DSH_HOME ?? path.join(os.homedir(), '.dsh')) {
  return path.join(dshHome, 'dsh-web-update')
}

/**
 * Render the restart helper.
 *
 * @param {object} options helper inputs
 * @param {number} options.oldPid pid of the Host that is about to exit
 * @param {string} options.nodeBin node executable of that Host
 * @param {string} options.cliPath the dsh entry script of that Host
 * @param {string[]} options.argv argv after the entry script (`['web','--no-open']`)
 * @param {string} options.cwd working directory for the new server
 * @param {string} options.host bind host used for the health probe
 * @param {number} options.port bind port used for the health probe
 * @param {string} options.oldVersion version to roll back to
 * @param {string} options.newVersion version that was just installed
 * @param {string} options.packageName package being updated
 * @param {string} options.npmCommand npm executable used for the rollback
 * @param {string[]} options.rollbackArgs npm argument template, `{target}` replaced
 * @param {string} options.logPath where the helper appends its log
 * @param {string} options.statusPath where the final outcome is written
 * @param {number} [options.timeoutSeconds] health-wait budget
 * @returns {string} bash script text
 */
export function buildRestartScript(options) {
  const timeoutSeconds = Math.max(20, Math.round(options.timeoutSeconds ?? 90))
  const healthIterations = timeoutSeconds * 2
  const rollbackTemplate = options.rollbackArgs ?? ['install', '-g', '--no-audit', '--no-fund', '{target}']
  const rollbackTarget = `${options.packageName}@${options.oldVersion ?? ''}`
  return `#!/usr/bin/env bash
# Generated by dsh-web-update at ${new Date().toISOString()}.
# Restarts the dsh web Host after a self-update; safe to run detached.
set -u

OLD_PID=${quote(options.oldPid)}
LOG=${quote(options.logPath)}
STATUS_FILE=${quote(options.statusPath)}
CWD=${quote(options.cwd ?? process.cwd())}
NODE_BIN=${quote(options.nodeBin)}
CLI_PATH=${quote(options.cliPath)}
PROBE_HOST=${quote(options.host ?? '127.0.0.1')}
PROBE_PORT=${quote(options.port ?? 3080)}
OLD_VERSION=${quote(options.oldVersion ?? '')}
NEW_VERSION=${quote(options.newVersion ?? '')}
PACKAGE_NAME=${quote(options.packageName)}
NPM=${quote(options.npmCommand)}
HEALTH_ITERATIONS=${quote(healthIterations)}
ARGS=${arrayLiteral(options.argv ?? ['web', '--no-open'])}
ROLLBACK_ARGS=${arrayLiteral(expandTarget(rollbackTemplate, rollbackTarget))}
NEW_PID=0

log() { printf '%s %s\\n' "$(date -Is)" "$*" >> "$LOG"; }

write_status() { # status detail
  printf '{"status":"%s","detail":"%s","from":"%s","to":"%s","pid":%s,"at":"%s"}\\n' \\
    "$1" "$2" "$OLD_VERSION" "$NEW_VERSION" "$NEW_PID" "$(date -Is)" > "$STATUS_FILE" 2>/dev/null
  log "outcome: $1 - $2"
}

port_open() { (exec 3<>"/dev/tcp/$PROBE_HOST/$PROBE_PORT") 2>/dev/null; }

wait_port_closed() { # iterations
  local i
  for ((i = 0; i < $1; i += 1)); do
    port_open || return 0
    sleep 0.25
  done
  return 1
}

spawn_server() {
  if ! cd "$CWD" 2>/dev/null; then cd /; fi
  nohup "$NODE_BIN" "$CLI_PATH" "\${ARGS[@]}" >> "$LOG" 2>&1 &
  NEW_PID=$!
  log "spawned dsh web pid $NEW_PID: $NODE_BIN $CLI_PATH \${ARGS[*]} (cwd $CWD)"
}

wait_healthy() {
  local i
  for ((i = 0; i < HEALTH_ITERATIONS; i += 1)); do
    if ! kill -0 "$NEW_PID" 2>/dev/null; then
      log "new dsh web process $NEW_PID exited before it listened on $PROBE_HOST:$PROBE_PORT"
      return 1
    fi
    if port_open; then
      # The listener starts before the Loader settles; require it to stay alive.
      sleep 3
      if kill -0 "$NEW_PID" 2>/dev/null && port_open; then
        log "new dsh web pid $NEW_PID is alive and listening on $PROBE_HOST:$PROBE_PORT"
        return 0
      fi
      log "new dsh web pid $NEW_PID stopped listening or exited during boot"
      return 1
    fi
    sleep 0.5
  done
  log "timed out waiting for the new dsh web to listen on $PROBE_HOST:$PROBE_PORT"
  return 1
}

log "restart helper started for dsh web pid $OLD_PID; package $PACKAGE_NAME $OLD_VERSION -> $NEW_VERSION"
for ((i = 0; i < 240; i += 1)); do
  kill -0 "$OLD_PID" 2>/dev/null || break
  sleep 0.25
done
if kill -0 "$OLD_PID" 2>/dev/null; then
  log "old dsh web pid $OLD_PID still alive after 60s; sending SIGTERM"
  kill -TERM "$OLD_PID" 2>/dev/null
  for ((i = 0; i < 60; i += 1)); do
    kill -0 "$OLD_PID" 2>/dev/null || break
    sleep 0.25
  done
  if kill -0 "$OLD_PID" 2>/dev/null; then
    log "old dsh web pid $OLD_PID ignored SIGTERM; sending SIGKILL"
    kill -KILL "$OLD_PID" 2>/dev/null
    sleep 0.5
  fi
fi
log "old dsh web pid $OLD_PID is gone"
if ! wait_port_closed 80; then
  log "warning: $PROBE_HOST:$PROBE_PORT is still accepting connections after the old pid exited"
fi

spawn_server
if wait_healthy; then
  write_status "restarted" "new dsh web is serving"
  log "restart complete"
  exit 0
fi

if [ -n "$OLD_VERSION" ]; then
  log "rolling $PACKAGE_NAME back to $OLD_VERSION"
  if "$NPM" "\${ROLLBACK_ARGS[@]}" >> "$LOG" 2>&1; then
    log "rollback install finished"
    spawn_server
    if wait_healthy; then
      write_status "rolled-back" "new version did not start; rolled back to $OLD_VERSION"
      log "restart complete on the rolled-back version"
      exit 0
    fi
    write_status "failed" "new version and rollback both failed to start"
    log "rollback start also failed; the server is down"
    exit 1
  fi
  write_status "failed" "rollback install failed; the server is down"
  log "rollback install failed; the server is down"
  exit 1
fi

write_status "failed" "new version did not start and no rollback version is known"
log "no rollback version known; the server is down"
exit 1
`
}

/**
 * Write and start the detached restart helper.
 *
 * @param {{stateDir: string, script: string, env?: NodeJS.ProcessEnv}} request helper request
 * @returns {{scriptPath: string, child: import('node:child_process').ChildProcess}} spawned helper
 */
export function spawnRestartHelper(request) {
  mkdirSync(request.stateDir, { recursive: true })
  const scriptPath = path.join(request.stateDir, 'restart-dsh-web.sh')
  writeFileSync(scriptPath, request.script, { encoding: 'utf8', mode: 0o755 })
  try {
    chmodSync(scriptPath, 0o755)
  } catch {
    /* the write already set the mode */
  }
  const child = spawn('/bin/bash', [scriptPath], {
    cwd: request.stateDir,
    env: request.env ?? process.env,
    detached: true,
    stdio: 'ignore',
  })
  child.unref()
  return { scriptPath, child }
}
